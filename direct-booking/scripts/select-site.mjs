#!/usr/bin/env node
// Chooses which host's site both apps build, from the SITE_ID env var.
//
// Writes two gitignored files:
//   sites/selected.ts        re-exports sites/<SITE_ID>/site.ts (imported by both apps)
//   apps/api/wrangler.jsonc  apps/api/wrangler.base.json + sites/<SITE_ID>/cloudflare.json
//
// Without SITE_ID it keeps the site chosen last time, so `SITE_ID=x npm run site`
// once is enough. Run by the apps' predev/prebuild scripts, so the files stay fresh.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sitesDir = join(root, "sites");
const selectedFile = join(sitesDir, "selected.ts");
const apiDir = join(root, "apps", "api");

const available = readdirSync(sitesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(sitesDir, d.name, "site.ts")))
  .map((d) => d.name);

function previousSelection() {
  if (!existsSync(selectedFile)) return undefined;
  return readFileSync(selectedFile, "utf8").match(/export const SITE_ID = "([^"]+)"/)?.[1];
}

const siteId = process.env.SITE_ID || previousSelection();
if (!siteId) {
  fail(`SITE_ID is not set and no site has been selected yet.\nRun: SITE_ID=<id> npm run site`);
}
if (!available.includes(siteId)) {
  fail(`Unknown SITE_ID "${siteId}".`);
}

writeFileSync(
  selectedFile,
  `// Generated by scripts/select-site.mjs. Do not edit; set SITE_ID instead.
export const SITE_ID = "${siteId}";
export { default as site } from "./${siteId}/site";
`,
);

const base = readJson(join(apiDir, "wrangler.base.json"));
const deploy = readJson(join(sitesDir, siteId, "cloudflare.json"));
const wrangler = {
  ...base,
  name: deploy.workerName,
  vars: { ...base.vars, SITE_ID: siteId },
  d1_databases: base.d1_databases.map((db) => ({
    ...db,
    database_name: deploy.d1.databaseName,
    database_id: deploy.d1.databaseId,
  })),
  ...(deploy.routes?.length ? { routes: deploy.routes } : {}),
};
writeFileSync(
  join(apiDir, "wrangler.jsonc"),
  `// Generated by scripts/select-site.mjs for SITE_ID=${siteId}. Do not edit.
// Shared settings: apps/api/wrangler.base.json. Per-site: sites/${siteId}/cloudflare.json.
${JSON.stringify(wrangler, null, 2)}
`,
);

console.log(`Site: ${siteId}`);

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function fail(message) {
  console.error(`${message}\nAvailable sites: ${available.join(", ") || "(none)"}`);
  process.exit(1);
}
